-- 목표 브리지는 이제 로봇 위치가 아니라 '막은 물건(저장 지도에 없는 장애물)이 이 구역 안에 있는가'로 비상구 앞 적재를 가린다.
-- 그래서 구역에 통로로 들어가는 문(x 7.0~7.2)이 걸치면 문을 막은 물건까지 비상구 앞 적재로 잘못 볼 수 있다 → 복도 안쪽만.
-- 관리자가 이미 다른 값으로 고쳤으면 그대로 둔다.
UPDATE inspection_point SET exit_zone = '[7.15, 3.6, 8.2, 7.2]', updated_at = now()
 WHERE code = 'P3' AND exit_zone = '[7.1, 3.6, 8.2, 7.2]'::jsonb;
